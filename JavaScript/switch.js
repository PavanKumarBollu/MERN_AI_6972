let day = "Sat";

switch (day) {
  case "Mon":
    console.log(day + "Start of the week");
    break;
  case "Tue":
    console.log(day + "Start of the week");
    break;
  case "Wed":
    console.log(day + "Mid of the week");
    break;
  case "Thu":
    console.log(day + "Mid of the week");
    break;
  case "Fri":
    console.log(day + "End of the week");
    break;
  case "Sat":
    console.log(day + "Start of the week");
    break;
  default:
    console.log(day + "This is default case");
    break;
}
